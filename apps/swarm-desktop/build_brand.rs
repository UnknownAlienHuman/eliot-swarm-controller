//! Generates `brand.rs` from the brand book's tokens (`design/tokens.json`,
//! the "Eliot Swarm Material" design system): the six themes' color roles,
//! their shadows, and the size, shape, spacing, opacity, motion, icon and
//! type tokens. The desktop reads these constants, never a copy of them.

use std::fmt::Write as _;
use std::path::Path;

use serde_json::Value;

const THEMES: [&str; 6] = ["light", "dark", "amoled", "purple", "neon", "matrix"];

pub fn generate(tokens: &Path, out: &Path) {
    println!("cargo:rerun-if-changed={}", tokens.display());
    let text = std::fs::read_to_string(tokens).expect("design/tokens.json is readable");
    let root: Value = serde_json::from_str(&text).expect("design/tokens.json is JSON");
    let mut code = String::from("// Generated by build_brand.rs from design/tokens.json.\n\n");
    colors(&root, &mut code);
    shadows(&root, &mut code);
    scalars(&root, &mut code);
    types(&root, &mut code);
    std::fs::write(out, code).expect("brand.rs is writable");
}

fn tokens<'a>(root: &'a Value, family: &str) -> &'a [Value] {
    root[family]["tokens"]
        .as_array()
        .unwrap_or_else(|| panic!("tokens.json has {family}.tokens"))
}

fn name(token: &Value) -> &str {
    checked(token["name"].as_str().expect("every token has a name"))
}

/// A token's usage as a one-line doc comment.
fn doc(token: &Value) -> String {
    token["usage"]
        .as_str()
        .unwrap_or("")
        .replace(char::is_control, " ")
}

/// Write `usage` as a doc comment at `indent`, or nothing when empty.
fn doc_line(code: &mut String, indent: &str, usage: &str) {
    if !usage.trim().is_empty() {
        writeln!(code, "{indent}/// {usage}").unwrap();
    }
}

/// A token name that makes a Rust identifier: lowercase ASCII words joined
/// by `-`, starting with a letter.
fn checked(name: &str) -> &str {
    let valid = name.starts_with(|c: char| c.is_ascii_lowercase())
        && name
            .bytes()
            .all(|b| b.is_ascii_lowercase() || b.is_ascii_digit() || b == b'-');
    assert!(
        valid,
        "token name {name:?} is not lowercase-words-with-dashes"
    );
    name
}

fn upper(name: &str) -> String {
    name.replace('-', "_").to_uppercase()
}

fn snake(name: &str) -> String {
    name.replace('-', "_")
}

/// `#rrggbb` or `#rrggbbaa` as `0xAARRGGBB`.
fn hex(value: &str) -> u32 {
    let digits = value.trim().trim_start_matches('#');
    let (rgb, alpha) = match digits.len() {
        6 => (digits, "ff"),
        8 => (&digits[..6], &digits[6..]),
        _ => panic!("color {value} is #rrggbb or #rrggbbaa"),
    };
    let rgb = u32::from_str_radix(rgb, 16).expect("hex color");
    let alpha = u32::from_str_radix(alpha, 16).expect("hex alpha");
    (alpha << 24) | rgb
}

/// One theme's value of a color token, following `var(--role)` aliases.
fn color_of(all: &[Value], token: &Value, theme: &str) -> u32 {
    color_at(all, token, theme, 0)
}

fn color_at(all: &[Value], token: &Value, theme: &str, depth: usize) -> u32 {
    assert!(depth < 8, "{} aliases itself in a cycle", name(token));
    let value = token["value"]
        .as_str()
        .or_else(|| token["value"][theme].as_str())
        .unwrap_or_else(|| panic!("{} has a {theme} value", name(token)));
    let alias = value
        .strip_prefix("var(--")
        .and_then(|v| v.strip_suffix(')'))
        .or_else(|| value.strip_prefix('{').and_then(|v| v.strip_suffix('}')));
    if let Some(alias) = alias {
        let target = all
            .iter()
            .find(|t| name(t) == alias)
            .unwrap_or_else(|| panic!("{} aliases a known role", name(token)));
        return color_at(all, target, theme, depth + 1);
    }
    hex(value)
}

fn colors(root: &Value, code: &mut String) {
    let all = tokens(root, "color");
    code.push_str("/// One theme's color roles as `0xAARRGGBB`.\n");
    code.push_str("#[derive(Clone, Copy, Debug, PartialEq, Eq)]\npub struct Scheme {\n");
    for token in all {
        let usage = doc(token);
        doc_line(code, "    ", &usage);
        writeln!(code, "    pub {}: u32,", snake(name(token))).unwrap();
    }
    code.push_str("}\n\n");
    code.push_str("/// The six themes in order: light, dark, amoled, purple, neon, matrix.\n");
    code.push_str("pub const SCHEMES: [Scheme; 6] = [\n");
    for theme in THEMES {
        code.push_str("    Scheme {\n");
        for token in all {
            writeln!(
                code,
                "        {}: {:#010x},",
                snake(name(token)),
                color_of(all, token, theme)
            )
            .unwrap();
        }
        code.push_str("    },\n");
    }
    code.push_str("];\n\n");
}

/// One CSS shadow layer: `x y blur [spread] color`.
fn shadow_layer(layer: &str) -> String {
    let (lengths, color) = match layer.find("rgba(") {
        Some(at) => {
            let inner = layer[at + 5..].trim_end_matches(')');
            let parts: Vec<f64> = inner
                .split(',')
                .map(|p| p.trim().parse().expect("rgba component"))
                .collect();
            let [r, g, b, a] = parts[..] else {
                panic!("rgba has four components")
            };
            let argb = (((a * 255.0).round() as u32) << 24)
                | ((r as u32) << 16)
                | ((g as u32) << 8)
                | (b as u32);
            (&layer[..at], argb)
        }
        None => {
            let at = layer.find('#').expect("a shadow color");
            (&layer[..at], hex(&layer[at..]))
        }
    };
    let px: Vec<f64> = lengths
        .split_whitespace()
        .map(|p| p.trim_end_matches("px").parse().expect("shadow length"))
        .collect();
    let (y, blur, spread) = match px[..] {
        [_, y, blur] => (y, blur, 0.0),
        [_, y, blur, spread] => (y, blur, spread),
        _ => panic!("shadow {layer} has three or four lengths"),
    };
    format!("Shadow {{ y: {y:?}, blur: {blur:?}, spread: {spread:?}, color: {color:#010x} }}")
}

fn shadows(root: &Value, code: &mut String) {
    code.push_str(
        "/// One shadow layer in DIPs, as CSS `box-shadow` (no x offset), color `0xAARRGGBB`.\n\
         #[derive(Clone, Copy, Debug, PartialEq)]\n\
         pub struct Shadow {\n    pub y: f64,\n    pub blur: f64,\n    pub spread: f64,\n    pub color: u32,\n}\n\n",
    );
    for token in tokens(root, "shadow") {
        let mut layers_per_theme = Vec::new();
        for theme in THEMES {
            let value = token["value"][theme]
                .as_str()
                .unwrap_or_else(|| panic!("{} has a {theme} shadow", name(token)));
            let layers: Vec<String> = if value == "none" {
                Vec::new()
            } else {
                value
                    .split("), ")
                    .map(|l| {
                        let l = l.trim();
                        if l.contains("rgba(") && !l.ends_with(')') {
                            shadow_layer(&format!("{l})"))
                        } else {
                            shadow_layer(l)
                        }
                    })
                    .collect()
            };
            layers_per_theme.push(layers);
        }
        let usage = doc(token);
        doc_line(code, "", &usage);
        writeln!(code, "pub const {}: [&[Shadow]; 6] = [", upper(name(token))).unwrap();
        for layers in layers_per_theme {
            writeln!(code, "    &[{}],", layers.join(", ")).unwrap();
        }
        code.push_str("];\n\n");
    }
}

fn number(value: &Value, unit: &str) -> f64 {
    match value {
        Value::Number(n) => n.as_f64().expect("number"),
        Value::String(s) => s
            .trim()
            .trim_end_matches(unit)
            .parse()
            .unwrap_or_else(|_| panic!("{s} is a number in {unit}")),
        _ => panic!("token value is a number"),
    }
}

fn scalars(root: &Value, code: &mut String) {
    for (family, unit) in [
        ("size", "px"),
        ("radius", "px"),
        ("spacing", "px"),
        ("opacity", ""),
        ("spring", "ms"),
        ("icon", ""),
    ] {
        for token in tokens(root, family) {
            let usage = doc(token);
            doc_line(code, "", &usage);
            writeln!(
                code,
                "pub const {}: f64 = {:?};",
                upper(name(token)),
                number(&token["value"], unit)
            )
            .unwrap();
        }
    }
    for token in tokens(root, "duration") {
        let usage = doc(token);
        doc_line(code, "", &usage);
        writeln!(
            code,
            "pub const {}: u64 = {};",
            upper(name(token)),
            number(&token["value"], "ms") as u64
        )
        .unwrap();
    }
    for token in tokens(root, "easing") {
        let value = token["value"].as_str().expect("easing");
        let inner = value
            .trim_start_matches("cubic-bezier(")
            .trim_end_matches(')');
        let usage = doc(token);
        doc_line(code, "", &usage);
        writeln!(
            code,
            "pub const {}: &str = \"{}\";",
            upper(name(token)),
            keyspline(inner)
        )
        .unwrap();
    }
    code.push('\n');
}

/// `x1, y1, x2, y2` as XAML's KeySpline takes it: `x1,y1 x2,y2`.
fn keyspline(points: &str) -> String {
    let p: Vec<&str> = points.split(',').map(str::trim).collect();
    let [x1, y1, x2, y2] = p[..] else {
        panic!("cubic-bezier has four points")
    };
    format!("{x1},{y1} {x2},{y2}")
}

fn types(root: &Value, code: &mut String) {
    code.push_str(
        "/// One type style: size and line height in DIPs, weight, letter spacing in DIPs.\n\
         #[derive(Clone, Copy, Debug, PartialEq)]\n\
         pub struct TypeStyle {\n    pub size: f64,\n    pub line_height: f64,\n    pub weight: u16,\n    pub letter_spacing: f64,\n    pub mono: bool,\n}\n\n",
    );
    let groups = root["type"]["groups"].as_array().expect("type.groups");
    for group in groups {
        let mono = group["family"].as_str() == Some("mono");
        for style in group["styles"]
            .as_array()
            .unwrap_or_else(|| panic!("type group {} has styles", group["name"]))
        {
            let usage = doc(style);
            doc_line(code, "", &usage);
            writeln!(
                code,
                "pub const {}: TypeStyle = TypeStyle {{ size: {:?}, line_height: {:?}, weight: {}, letter_spacing: {:?}, mono: {mono} }};",
                upper(name(style)),
                number(&style["fontSize"], "px"),
                number(&style["lineHeight"], "px"),
                style["fontWeight"]
                    .as_u64()
                    .unwrap_or_else(|| panic!("{} has a numeric fontWeight", name(style))),
                style.get("letterSpacing").map_or(0.0, |v| number(v, "px")),
            )
            .unwrap();
        }
    }
}
